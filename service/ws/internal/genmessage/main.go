// Command genmessage generates the Go types used to send selected /ws events.
package main

import (
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

const schemaPrefix = "#/components/schemas/"

type schema struct {
	Ref           string            `yaml:"$ref"`
	Type          string            `yaml:"type"`
	Format        string            `yaml:"format"`
	Enum          []any             `yaml:"enum"`
	Nullable      bool              `yaml:"nullable"`
	Properties    map[string]schema `yaml:"properties"`
	Required      []string          `yaml:"required"`
	Discriminator struct {
		Mapping map[string]string `yaml:"mapping"`
	} `yaml:"discriminator"`
}

type schemas map[string]schema

func (s schemas) resolve(ref string) (string, schema, error) {
	name, ok := strings.CutPrefix(ref, schemaPrefix)
	definition, found := s[name]
	if !ok || !found {
		return "", schema{}, fmt.Errorf("unknown schema reference %q", ref)
	}
	return name, definition, nil
}

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: genmessage <openapi.yaml> <output.go>")
	}
	source, err := generate(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[2], source, 0o644); err != nil {
		log.Fatal(err)
	}
}

func generate(path string) ([]byte, error) {
	input, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var spec struct {
		Components struct {
			Schemas schemas `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(input, &spec); err != nil {
		return nil, err
	}

	var definitions []byte
	models := spec.Components.Schemas
	for _, event := range []string{"PING", "MESSAGE_CREATED"} {
		definitions, err = appendMessage(definitions, models, event)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", event, err)
		}
	}

	header := []byte("// Code generated by genmessage from docs/v3-api.yaml. DO NOT EDIT.\n\npackage ws\n")
	if strings.Contains(string(definitions), "uuid.UUID") {
		header = append(header, "\nimport \"github.com/gofrs/uuid\"\n"...)
	}
	return format.Source(append(header, definitions...))
}

func appendMessage(out []byte, models schemas, event string) ([]byte, error) {
	ref := models["WebSocketMessage"].Discriminator.Mapping[event]
	name, message, err := models.resolve(ref)
	if err != nil {
		return nil, err
	}
	name = strings.TrimPrefix(name, "WebSocket")
	if len(message.Properties) != 2 || !slices.Contains(message.Required, "type") || !slices.Contains(message.Required, "body") {
		return nil, fmt.Errorf("expected required type and body properties")
	}

	_, tag, err := models.resolve(message.Properties["type"].Ref)
	if err != nil {
		return nil, err
	}
	if tag.Type != "string" || tag.Nullable || len(tag.Enum) != 1 || tag.Enum[0] != event {
		return nil, fmt.Errorf("expected type to be the literal %q", event)
	}

	body := message.Properties["body"]
	if body.Ref != "" {
		_, body, err = models.resolve(body.Ref)
		if err != nil {
			return nil, err
		}
	}

	out = fmt.Appendf(out, "\n// %s is the %s WebSocket message.\n", name, event)
	bodyExpr := "m"
	switch {
	case body.Nullable && len(body.Enum) == 1 && body.Enum[0] == nil:
		out = fmt.Appendf(out, "type %s struct{}\n", name)
		bodyExpr = "nil"
	case body.Type == "object" && !body.Nullable && len(body.Required) == len(body.Properties):
		out = fmt.Appendf(out, "type %s struct {\n", name)
		for _, key := range body.Required {
			field, err := fieldName(key)
			if err != nil {
				return nil, err
			}
			property := body.Properties[key]
			switch {
			case property.Type == "string" && property.Format == "uuid" && !property.Nullable:
				out = fmt.Appendf(out, "\t%s uuid.UUID `json:%q`\n", field, key)
			case property.Type == "boolean" && !property.Nullable:
				out = fmt.Appendf(out, "\t%s bool `json:%q`\n", field, key)
			default:
				return nil, fmt.Errorf("unsupported body property %q", key)
			}
		}
		out = append(out, "}\n"...)
	default:
		return nil, fmt.Errorf("expected a null body or an object with required properties")
	}
	return fmt.Appendf(out, "\nfunc (m %s) asMessage() *message {\n\treturn makeMessage(%q, %s)\n}\n", name, event, bodyExpr), nil
}

func fieldName(key string) (string, error) {
	var name strings.Builder
	for _, part := range strings.Split(key, "_") {
		if part == "" {
			return "", fmt.Errorf("unsupported body property name %q", key)
		}
		if part == "id" {
			name.WriteString("ID")
		} else {
			name.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return name.String(), nil
}
