package main

import (
	"fmt"
	"go/format"
	"log"
	"maps"
	"os"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

const schemaPrefix = "#/components/schemas/"

type schema struct {
	Ref                  string            `yaml:"$ref"`
	Type                 string            `yaml:"type"`
	Format               string            `yaml:"format"`
	Enum                 []any             `yaml:"enum"`
	Nullable             bool              `yaml:"nullable"`
	Properties           map[string]schema `yaml:"properties"`
	Required             []string          `yaml:"required"`
	Items                *schema           `yaml:"items"`
	AdditionalProperties *schema           `yaml:"additionalProperties"`
	Discriminator        struct {
		Mapping map[string]string `yaml:"mapping"`
	} `yaml:"discriminator"`
}

type generator struct {
	schemas map[string]schema
	types   map[string]string
	methods []byte
}

func (g *generator) resolve(ref string) (string, schema, error) {
	name, ok := strings.CutPrefix(ref, schemaPrefix)
	definition, found := g.schemas[name]
	if !ok || !found {
		return "", schema{}, fmt.Errorf("unknown schema reference %q", ref)
	}
	return name, definition, nil
}

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: genmessage <openapi.yaml> <output.go>")
	}
	source, err := generate(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[2], source, 0o644); err != nil {
		log.Fatal(err)
	}
}

func generate(path string) ([]byte, error) {
	input, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var spec struct {
		Components struct {
			Schemas map[string]schema `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(input, &spec); err != nil {
		return nil, err
	}

	g := generator{schemas: spec.Components.Schemas, types: make(map[string]string)}
	events := g.schemas["WebSocketMessage"].Discriminator.Mapping
	if len(events) == 0 {
		return nil, fmt.Errorf("WebSocketMessage has no event mappings")
	}
	for _, event := range slices.Sorted(maps.Keys(events)) {
		if err := g.addMessage(event, events[event]); err != nil {
			return nil, fmt.Errorf("%s: %w", event, err)
		}
	}

	var definitions strings.Builder
	for _, name := range slices.Sorted(maps.Keys(g.types)) {
		fmt.Fprintf(&definitions, "\ntype %s %s\n", name, g.types[name])
	}

	header := []byte("// Code generated by genmessage from docs/v3-api.yaml. DO NOT EDIT.\n\npackage ws\n")
	var imports []string
	if strings.Contains(definitions.String(), "time.Time") {
		imports = append(imports, "\"time\"")
	}
	if strings.Contains(definitions.String(), "uuid.UUID") {
		if len(imports) != 0 {
			imports = append(imports, "")
		}
		imports = append(imports, "\"github.com/gofrs/uuid\"")
	}
	if len(imports) != 0 {
		header = fmt.Appendf(header, "\nimport (\n%s\n)\n", strings.Join(imports, "\n"))
	}
	return format.Source(append(append(header, definitions.String()...), g.methods...))
}

func (g *generator) addMessage(event, ref string) error {
	name, message, err := g.resolve(ref)
	if err != nil {
		return err
	}
	name = strings.TrimPrefix(name, "WebSocket")
	if len(message.Properties) != 2 || !slices.Contains(message.Required, "type") || !slices.Contains(message.Required, "body") {
		return fmt.Errorf("expected required type and body properties")
	}

	_, tag, err := g.resolve(message.Properties["type"].Ref)
	if err != nil {
		return err
	}
	if tag.Type != "string" || tag.Nullable || len(tag.Enum) != 1 || tag.Enum[0] != event {
		return fmt.Errorf("expected type to be the literal %q", event)
	}

	body := message.Properties["body"]
	expr := "m"
	if body.Nullable && len(body.Enum) == 1 && body.Enum[0] == nil {
		g.types[name] = "struct{}"
		expr = "nil"
	} else {
		bodyType, err := g.goType(name, body)
		if err != nil {
			return err
		}
		if name != bodyType {
			g.types[name] = bodyType
		}
	}
	g.methods = fmt.Appendf(g.methods, "\nfunc (m %s) asMessage() *message {\n\treturn makeMessage(%q, %s)\n}\n", name, event, expr)
	return nil
}

func (g *generator) goType(name string, definition schema) (string, error) {
	if definition.Ref != "" {
		refName, resolved, err := g.resolve(definition.Ref)
		if err != nil {
			return "", err
		}
		name = strings.TrimPrefix(refName, "WebSocket")
		if name == "Session" {
			name = "WebRTCSession" // Session is the existing WebSocket connection interface.
		}
		definition = resolved
	}
	if definition.Nullable {
		return "", fmt.Errorf("unsupported nullable type %s", name)
	}
	switch definition.Type {
	case "string":
		switch definition.Format {
		case "":
			return "string", nil
		case "uuid":
			return "uuid.UUID", nil
		case "date-time":
			return "time.Time", nil
		}
	case "boolean":
		return "bool", nil
	case "integer":
		return "int", nil
	case "array":
		if definition.Items != nil {
			item, err := g.goType(name+"Item", *definition.Items)
			return "[]" + item, err
		}
	case "object":
		if definition.AdditionalProperties != nil && len(definition.Properties) == 0 {
			value, err := g.goType(name+"Value", *definition.AdditionalProperties)
			return "map[string]" + value, err
		}
		return name, g.addObject(name, definition)
	}
	return "", fmt.Errorf("unsupported schema for %s: %s %s", name, definition.Type, definition.Format)
}

func (g *generator) addObject(name string, definition schema) error {
	if _, found := g.types[name]; found {
		return nil
	}
	g.types[name] = "" // Reserve the name before resolving nested references.
	var fields strings.Builder
	fields.WriteString("struct {\n")
	for _, key := range slices.Sorted(maps.Keys(definition.Properties)) {
		field, err := fieldName(key)
		if err != nil {
			return err
		}
		typ, err := g.goType(name+field, definition.Properties[key])
		if err != nil {
			return err
		}
		tag := key
		if !slices.Contains(definition.Required, key) {
			typ = "*" + typ
			tag += ",omitempty"
		}
		fmt.Fprintf(&fields, "\t%s %s `json:%q`\n", field, typ, tag)
	}
	fields.WriteString("}")
	g.types[name] = fields.String()
	return nil
}

func fieldName(key string) (string, error) {
	var name strings.Builder
	for _, part := range strings.Split(key, "_") {
		switch part {
		case "":
			return "", fmt.Errorf("unsupported body property name %q", key)
		case "id":
			name.WriteString("ID")
		case "dm":
			name.WriteString("DM")
		default:
			stem, hasID := strings.CutSuffix(part, "Id")
			name.WriteString(strings.ToUpper(stem[:1]) + stem[1:])
			if hasID {
				name.WriteString("ID")
			}
		}
	}
	return name.String(), nil
}
